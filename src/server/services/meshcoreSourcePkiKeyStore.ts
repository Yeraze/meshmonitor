/**
 * MeshCoreSourcePkiKeyStore
 *
 * Encrypts and persists a MeshCore Companion source's OWN Ed25519 identity
 * private key (orlp format), captured automatically on connect. The server
 * uses it to derive the X25519 DM shared secret for each peer and decrypt our
 * own re-flooded direct messages, so #6194 heard-by matching can disambiguate
 * echoes that collide on the 1-byte src/dest hash prefix (issue #6195).
 *
 * Structural copy of `MeshCoreObserverKeyStore` / `SourcePkiKeyStore`:
 * AES-256-GCM with an HKDF-derived key from `SESSION_SECRET`, with an envelope
 * `kid` so a rotated secret is detected (`key_rotated`) rather than silently
 * failing with an auth-tag error.
 *
 * KDF info strings are deliberately NEW and distinct from every other store
 * ('source-pki-key-*', 'meshcore-observer-key-*', 'meshcore-admin-creds-*') —
 * this is the load-bearing difference from those models. Reusing an existing
 * info string would mean a leaked SESSION_SECRET plus a copy of this table
 * could be decrypted by code that only knows another store's derivation, or
 * vice versa; distinct info strings key-separate the stores even though they
 * share one secret.
 *
 * Threat model (same as the sibling stores):
 *   - Defends against a DB-file-only exfil (someone grabs `meshmonitor.db`
 *     without the host environment).
 *   - Does NOT defend against host compromise. Anyone running code on the host
 *     can read SESSION_SECRET and the DB.
 *
 * Capability gating: when SESSION_SECRET was NOT explicitly configured
 * (auto-generated by the environment loader), `canStore` is false — an
 * ephemeral key would lose the stored private key on every restart.
 *
 * ACCESS: admin-only, server-side only. This key material is never exposed
 * through any route or the settings API.
 */
import crypto from 'node:crypto';
import databaseService from '../../services/database.js';
import { logger } from '../../utils/logger.js';
import { getEnvironmentConfig } from '../config/environment.js';

/** KDF version stamped into each envelope. Bump if the HKDF info-strings or
 *  AEAD parameters ever change so old rows route through key_rotated. */
const KDF_VERSION = 1;
const KDF_INFO_AEAD = 'meshcore-source-pki-key-aead-v1';
const KDF_INFO_FINGERPRINT = 'meshcore-source-pki-key-fingerprint-v1';

interface StoredEnvelope {
  v: number;
  kid: string;
  iv: string;
  ct: string;
  tag: string;
}

export interface SourcePkiKeyCapability {
  canStore: boolean;
  /** Human-readable explanation when canStore=false, surfaced to the UI. */
  reason?: string;
}

export type SourcePkiKeyLoadResult =
  | { kind: 'none' }
  | { kind: 'ok'; privateKeyHex: string; publicKeyHex: string | null; keyMismatch: boolean }
  | { kind: 'key_rotated'; storedKid: string };

export interface SourcePkiKeyStatus {
  stored: boolean;
  /** 32-byte Ed25519 hex. Not secret — broadcast in every ADVERT. */
  publicKey: string | null;
  keyMismatch: boolean;
  updatedAt: number | null;
  /** True when an envelope exists but was encrypted under a different SESSION_SECRET. */
  keyRotated: boolean;
  canStore: boolean;
  reason: string | null;
}

export class MeshCoreSourcePkiKeyStore {
  private readonly aeadKey: Buffer;
  private readonly currentKid: string;
  private readonly _capability: SourcePkiKeyCapability;

  constructor(sessionSecret: string, sessionSecretProvided: boolean) {
    this._capability = sessionSecretProvided
      ? { canStore: true }
      : {
          canStore: false,
          reason:
            'SESSION_SECRET was not configured; an auto-generated value is in use. ' +
            'A stored MeshCore device key would be unrecoverable on every restart. ' +
            'Set SESSION_SECRET=$(openssl rand -hex 32) to enable device-key capture.',
        };
    const ikm = Buffer.from(sessionSecret, 'utf8');
    this.aeadKey = hkdfBytes(ikm, KDF_INFO_AEAD, 32);
    this.currentKid = hkdfBytes(ikm, KDF_INFO_FINGERPRINT, 4).toString('hex');
  }

  get capability(): SourcePkiKeyCapability {
    return this._capability;
  }

  /** First 8 hex chars of the HKDF fingerprint of the current SESSION_SECRET.
   *  Exposed mostly for tests; consumers should use `load()`/`status()` and
   *  react to `key_rotated`/`keyRotated` rather than comparing fingerprints. */
  get currentFingerprint(): string {
    return this.currentKid;
  }

  /**
   * Encrypt and persist `privateKeyHex` (orlp private-key hex, stored as UTF-8
   * text) for a source, alongside the clear `publicKeyHex` (32-byte Ed25519
   * hex, not secret). A fresh store clears any key-mismatch flag. Throws when
   * SESSION_SECRET is auto-generated — callers must check `capability` first.
   */
  async store(sourceId: string, privateKeyHex: string, publicKeyHex: string): Promise<void> {
    if (!this._capability.canStore) {
      throw new Error('Cannot persist MeshCore device key: SESSION_SECRET is auto-generated');
    }
    const iv = crypto.randomBytes(12);
    const cipher = crypto.createCipheriv('aes-256-gcm', this.aeadKey, iv);
    const ct = Buffer.concat([cipher.update(Buffer.from(privateKeyHex, 'utf8')), cipher.final()]);
    const tag = cipher.getAuthTag();
    const envelope: StoredEnvelope = {
      v: KDF_VERSION,
      kid: this.currentKid,
      iv: iv.toString('hex'),
      ct: ct.toString('hex'),
      tag: tag.toString('hex'),
    };
    await databaseService.meshcoreSourcePkiKeys.upsert(sourceId, JSON.stringify(envelope), publicKeyHex, 0);
  }

  /**
   * Load + decrypt the stored private key for a source. Returns one of:
   *   - `{ kind: 'none' }` when nothing is saved.
   *   - `{ kind: 'ok', privateKeyHex, publicKeyHex, keyMismatch }` on success.
   *   - `{ kind: 'key_rotated', storedKid }` when the envelope was encrypted
   *     with a different SESSION_SECRET.
   */
  async load(sourceId: string): Promise<SourcePkiKeyLoadResult> {
    const row = await databaseService.meshcoreSourcePkiKeys.getBySourceId(sourceId);
    if (!row) return { kind: 'none' };

    let env: StoredEnvelope;
    try {
      env = JSON.parse(row.encryptedPrivateKey) as StoredEnvelope;
    } catch {
      logger.warn(`[MeshCoreSourcePkiKeyStore] Malformed key envelope for ${sourceId}; treating as rotated`);
      return { kind: 'key_rotated', storedKid: '?' };
    }
    if (env.v !== KDF_VERSION || env.kid !== this.currentKid) {
      return { kind: 'key_rotated', storedKid: env.kid ?? '?' };
    }
    try {
      const decipher = crypto.createDecipheriv('aes-256-gcm', this.aeadKey, Buffer.from(env.iv, 'hex'));
      decipher.setAuthTag(Buffer.from(env.tag, 'hex'));
      const pt = Buffer.concat([decipher.update(Buffer.from(env.ct, 'hex')), decipher.final()]);
      return {
        kind: 'ok',
        privateKeyHex: pt.toString('utf8'),
        publicKeyHex: row.publicKey ?? null,
        keyMismatch: row.keyMismatch === 1,
      };
    } catch (err) {
      // kid matched but decrypt failed. Either an upgrade hazard or row
      // corruption — treat as rotated so callers re-capture rather than
      // silently proceeding with a broken key.
      logger.warn(
        `[MeshCoreSourcePkiKeyStore] Key decrypt failed for ${sourceId} despite matching kid: ${(err as Error).message}`,
      );
      return { kind: 'key_rotated', storedKid: env.kid };
    }
  }

  /** Clear any stored key for a source. No-op if none exists. */
  async clear(sourceId: string): Promise<void> {
    await databaseService.meshcoreSourcePkiKeys.deleteBySourceId(sourceId);
  }

  /**
   * Report status without attempting decryption: compares the envelope's
   * `v`/`kid` against the current fingerprint only. Never returns `storedKid`
   * — exposing it would let a hostile script fingerprint SESSION_SECRET
   * rotations across requests.
   */
  async status(sourceId: string): Promise<SourcePkiKeyStatus> {
    const row = await databaseService.meshcoreSourcePkiKeys.getBySourceId(sourceId);
    if (!row) {
      return {
        stored: false,
        publicKey: null,
        keyMismatch: false,
        updatedAt: null,
        keyRotated: false,
        canStore: this._capability.canStore,
        reason: this._capability.reason ?? null,
      };
    }

    let keyRotated: boolean;
    try {
      const env = JSON.parse(row.encryptedPrivateKey) as StoredEnvelope;
      keyRotated = env.v !== KDF_VERSION || env.kid !== this.currentKid;
    } catch {
      keyRotated = true;
    }

    return {
      stored: true,
      publicKey: row.publicKey ?? null,
      keyMismatch: row.keyMismatch === 1,
      updatedAt: row.updatedAt,
      keyRotated,
      canStore: this._capability.canStore,
      reason: this._capability.reason ?? null,
    };
  }
}

/**
 * HKDF-SHA256 wrapper returning a Buffer. We use a stable zero salt because the
 * IKM (SESSION_SECRET) is itself high-entropy and we need the derivation to be
 * deterministic — persisting a random salt in the DB would re-introduce the
 * key-rotation problem we're trying to detect.
 */
function hkdfBytes(ikm: Buffer, info: string, length: number): Buffer {
  const salt = Buffer.alloc(32);
  return Buffer.from(crypto.hkdfSync('sha256', ikm, salt, info, length));
}

// ---------------------------------------------------------------------------
// Module-level singleton — lazily constructed so tests can inject their own
// secret via `setMeshCoreSourcePkiKeyStoreForTesting`. The runtime path
// initializes from the environment config on first access.
// ---------------------------------------------------------------------------

let singleton: MeshCoreSourcePkiKeyStore | null = null;

export function getMeshCoreSourcePkiKeyStore(): MeshCoreSourcePkiKeyStore {
  if (!singleton) {
    const { sessionSecret, sessionSecretProvided } = getEnvironmentConfig();
    singleton = new MeshCoreSourcePkiKeyStore(sessionSecret, sessionSecretProvided);
  }
  return singleton;
}

/** Test hook: replace the singleton with a custom instance, or pass null to
 *  force re-initialization on the next access. */
export function setMeshCoreSourcePkiKeyStoreForTesting(store: MeshCoreSourcePkiKeyStore | null): void {
  singleton = store;
}
